console.log("\n[8] 표 자체 — 두 표에 같은 것을 묻는다");
// ---------------------------------------------------------------------------

// 표마다 따로 적으면 새 불변조건이 한쪽에만 붙는다. 실제로 그랬다 —
// 「/g 를 쓰지 않는다」에 lastIndex 설명이 한쪽에만 달려 있었다.
for (const [이름, cues, labelsOf, 갈래수, names] of [
  ["결재", BASIS_CUES, basisLabels, 6, BASIS_CUE_NAMES],
  ["인계서", ISSUE_CUES, issueLabels, 5, ISSUE_CUE_NAMES],
]) {
  ok(`${이름} — 갈래가 ${갈래수}이다`, cues.length === 갈래수, `${cues.length}개`);
  ok(
    `${이름} — 이름표가 겹치지 않는다`,
    new Set(cues.map((c) => c.label)).size === cues.length,
  );
  // 전역·고정 플래그가 붙으면 lastIndex 가 남아 같은 글에 두 번 물으면 답이
  // 달라진다. 그 두 플래그가 없다는 것이 곧 「두 번 물어도 같은 답」이다.
  ok(
    `${이름} — lastIndex 를 남기는 플래그(/g·/y)를 쓰지 않는다`,
    cues.every((c) => !c.test.global && !c.test.sticky),
    cues
      .filter((c) => c.test.global || c.test.sticky)
      .map((c) => c.label)
      .join(","),
  );
  ok(`${이름} — 빈 글에는 아무 이름표도 안 붙는다`, labelsOf("").length === 0);

  // 근거 꼬리표에 적히는 갈래 이름이 표에서 나와야 한다. 두 표 모두 이 목록을
  // 문장에 손으로 적어 두었고, 두 곳 다 이미 어긋나 있었다
  // (결재: 표는 「확인·회신」인데 문장은 「확인」 / 인계서: 「이견·유의」→「이견」).
  ok(
    `${이름} — 꼬리표 이름이 표에서 나온다`,
    cues.every((c) => names.includes(c.label)),
    names,
  );
  // 이름표에 이미 `·` 가 들어 있어(「확인·회신」·「이견·유의」) 잇는 기호까지
  // `·` 면 갈래 수가 부풀어 읽힌다.
  ok(
    `${이름} — 갈래를 쉼표로 잇는다`,
    names.split(", ").length === cues.length,
    names,
  );
}

console.log(
  `\n${fails.length === 0 ? "전부 통과" : "실패"} — ${pass}건 통과, ${fails.length}건 실패`,
);
if (fails.length > 0) {
  for (const f of fails) console.log(`  · ${f}`);
  process.exit(1);
}
