// 이게 이번에 물린 것의 정체다 — **넓게 잡기로 한 표가 좁게 잡기로 한 표보다
// 좁았다.** 결재 표가 「약속」으로 세는 어미는 인계서 표에서도 전부 걸려야 한다.
for (const 어미 of ["하기로 함", "하기로 했습니다", "하기로 하였음", "하기로 됐습니다"]) {
  const text = `8월 8일까지 반영본을 받${어미}`;
  const inApproval = basisLabels(text).includes("약속");
  const inHandover = issueLabels(text).includes("약속");
  ok(
    `「…받${어미}」 — 결재에서 약속이면 인계서에서도 약속`,
    !inApproval || inHandover,
    `결재 ${inApproval ? "○" : "×"} / 인계서 ${inHandover ? "○" : "×"}`,
  );
}

