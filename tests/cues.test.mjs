/**
 * 근거 규칙 시험 — 무엇이 「근거」라는 이름표를 달고 문서에 실리는가.
 *
 * **표가 둘이다.** 쓰임이 달라서 방향이 반대로 기울어 있고, 그래서 한 파일에서
 * 나란히 시험한다.
 *
 *   `approval-cues.ts` (BASIS_CUES) — 온나라로 나가는 결재 문서. **좁게** 잡는다
 *   `handover-cues.ts` (ISSUE_CUES) — 안에서 보는 인계서. **넓게** 잡는다
 *
 * 결재 쪽은 두 번 물렸다.
 *   ① 「까지·일정·법」을 낱말 그대로 잡아 인사이동 이야기가 「기한」 근거가 됐다
 *   ② 「기한」이 맨몸이라 **「얘기한·포기한·연기한·무기한」에 전부 걸렸다**
 *
 * 인계서 쪽은 **시험이 한 줄도 없었다.** 그래서 「약속」이 `/기로 했/` 하나뿐인
 * 채로 남아 있었고, 공문서 표준 문체인 개조식(「~하기로 함」)이 통째로 빠졌다.
 * 시연 데이터는 서술형이라 화면에서는 멀쩡해 보였다.
 *
 * 전부 화면을 열어 봐야만 보이는 종류였다. 그래서 규칙을 시험이 닿는 자리로
 * 옮기고, 물렸던 문장들을 여기에 못박는다.
 *
 * 돌리는 법
 *   npm run test:cues
 */

const { basisLabels, BASIS_CUES, BASIS_CUE_NAMES } = await import(
  "../src/lib/approval-cues.ts"
);
const { issueLabels, ISSUE_CUES, ISSUE_CUE_NAMES } = await import(
  "../src/lib/handover-cues.ts"
);

let pass = 0;
const fails = [];
function ok(name, cond, extra = "") {
  if (cond) {
    pass += 1;
    console.log(`  ✓ ${name}`);
  } else {
    fails.push(name + (extra ? ` — ${extra}` : ""));
    console.log(`  ✗ ${name}${extra ? ` — ${extra}` : ""}`);
  }
}

/**
 * 표 하나를 물어보는 두 함수를 만든다.
 *
 *   hits(글, 이름표)  걸려야 하는 것 — 걸리고, 이유가 이 이름표여야 한다
 *   misses(글)        걸리면 안 되는 것 — 한 이름표도 붙으면 안 된다
 *
 * 표마다 손으로 복사하면 실패 메시지 모양이 네 곳에 흩어지고, 표가 하나 더
 * 생길 때마다 또 둘이 늘어난다.
 */
function probes(labelsOf) {
  return {
    hits: (text, label) => {
      const labels = labelsOf(text);
      ok(
        `「${text.slice(0, 34)}…」 → ${label}`,
        labels.includes(label),
        `실제: [${labels.join(", ") || "없음"}]`,
      );
    },
    misses: (text) => {
      const labels = labelsOf(text);
      ok(
        `「${text.slice(0, 34)}…」 → 안 걸림`,
        labels.length === 0,
        `잘못 걸림: [${labels.join(", ")}]`,
      );
    },
  };
}

const { hits, misses } = probes(basisLabels);
const { hits: ihits, misses: imisses } = probes(issueLabels);

