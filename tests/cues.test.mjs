/**
 * 근거 규칙 시험 — 무엇이 「근거」라는 이름표를 달고 공문서에 실리는가.
 *
 * 이 표(`src/lib/approval-cues.ts`)는 온나라로 나가는 문서에 어느 대화가
 * 실릴지를 혼자 정한다. 두 번 물렸다.
 *
 *   ① 「까지·일정·법」을 낱말 그대로 잡아 인사이동 이야기가 「기한」 근거가 됐다
 *   ② 「기한」이 맨몸이라 **「얘기한·포기한·연기한·무기한」에 전부 걸렸다**
 *
 * 둘 다 화면을 열어 봐야만 보이는 종류였다. 그래서 규칙을 시험이 닿는 자리로
 * 옮기고, 물렸던 문장들을 여기에 못박는다.
 *
 * 돌리는 법
 *   npm run test:cues
 */

const { basisLabels, BASIS_CUES } = await import("../src/lib/approval-cues.ts");

let pass = 0;
const fails = [];
function ok(name, cond, extra = "") {
  if (cond) {
    pass += 1;
    console.log(`  ✓ ${name}`);
  } else {
    fails.push(name + (extra ? ` — ${extra}` : ""));
    console.log(`  ✗ ${name}${extra ? ` — ${extra}` : ""}`);
  }
}

/** 걸려야 하는 것 — 걸리고, 이유가 이 이름표여야 한다. */
function hits(text, label) {
  const labels = basisLabels(text);
  ok(
    `「${text.slice(0, 34)}…」 → ${label}`,
    labels.includes(label),
    `실제: [${labels.join(", ") || "없음"}]`,
  );
}

/** 걸리면 안 되는 것 — 한 이름표도 붙으면 안 된다. */
function misses(text) {
  const labels = basisLabels(text);
  ok(
    `「${text.slice(0, 34)}…」 → 안 걸림`,
    labels.length === 0,
    `잘못 걸림: [${labels.join(", ")}]`,
  );
}

// ---------------------------------------------------------------------------
console.log("\n[1] 시연 데이터의 진짜 근거 — 하나라도 빠지면 시연이 빈다");
// ---------------------------------------------------------------------------

// 아래 두 줄은 supabase/seed/demo.sql 과 src/lib/mock/works.ts 에 실재하는 대화다.
// 규칙을 좁히다가 이것들을 떨어뜨리면 「근거 꼬리표」 화면이 시연에서 비어 버린다.
hits(
  "2027년도 예산 요구서에 대행료를 반영해야 하는데, 최종보고가 8월 14일이면 요구서 제출 기한과 겹칩니다. 중간보고 수치라도 먼저 받을 수 있을까요?",
  "기한",
);
hits(
  "중간보고 수치는 권역 개편분이 반영되기 전이라 그대로 쓰면 안 됩니다. 8월 8일까지 반영본을 받기로 했으니 그때 공유드리겠습니다.",
  "약속",
);

// 조사를 열거하는 방식(`기한(이|은|을|까지)`)으로 가면 위 첫 줄의 「기한과」가
// 빠진다. 그 함정을 여기서 못박는다.
hits("요구서 제출 기한과 겹칩니다", "기한");
hits("제출 기한이 지났습니다", "기한");
hits("제출기한 임박", "기한");

// ---------------------------------------------------------------------------
console.log("\n[2] 두 번 물린 것 — 다시 걸리면 안 된다");
// ---------------------------------------------------------------------------

// ① 인계 이야기. 이 결재의 근거가 아니다.
misses(
  "정기인사로 이 업무를 이하람 주무관에게 넘기게 됐습니다. 최종보고 일정과 현안은 문서 4장에 정리해 두었습니다.",
);
// ② 「기한」이 맨몸이면 전부 걸리던 것들. 평범한 업무 어투다.
misses("아까 얘기한 대로 진행하겠습니다");
misses("어제 이야기한 부분은 반영했습니다");
misses("담당자가 제기한 내용을 검토 중입니다");
misses("그 건은 일단 포기한 상태입니다");
// 「회의」가 들어가면 「협의」로 걸리는 것이 맞다(아래 [3] 참조). 여기서 보려는
// 것은 「연기한」이 「기한」으로 걸리지 않는가이므로 회의라는 낱말을 뺀다.
misses("그 건은 다음 주로 연기한다고 합니다");
misses("무기한 보류되었습니다");
// 그 밖의 부분일치
misses("회의실 예약해 두었습니다");
misses("종합의견을 붙여 두었습니다");
misses("마감재 견본이 도착했습니다");
misses("문서 4장에 정리해 두었습니다");
misses("헌법소원 이야기는 아닙니다");
misses("그 방법으로 해 보겠습니다");

// ---------------------------------------------------------------------------
console.log("\n[3] 갈래마다 하나씩은 걸려야 한다");
// ---------------------------------------------------------------------------

hits("건축과와 협의를 마쳤습니다", "협의");
hits("실무 회의에서 나온 내용입니다", "협의");
hits("예산재정과에 확인했습니다", "확인·회신");
hits("검토 결과를 첨부합니다", "확인·회신");
hits("「폐기물관리법」 제14조에 따릅니다", "법령·기준");
hits("같은 법 시행규칙 제45조", "법령·기준");
hits("대행료는 5,200만원입니다", "금액·수치");
hits("전년 대비 3.8% 인상입니다", "금액·수치");
hits("8월 8일까지 반영본을 받기로 했습니다", "약속");

// ---------------------------------------------------------------------------
console.log("\n[4] 표 자체");
// ---------------------------------------------------------------------------

ok("갈래가 여섯이다", BASIS_CUES.length === 6, `${BASIS_CUES.length}개`);
ok(
  "이름표가 겹치지 않는다",
  new Set(BASIS_CUES.map((c) => c.label)).size === BASIS_CUES.length,
);
// 전역 플래그가 붙으면 lastIndex 가 남아 같은 글에 두 번 물으면 답이 달라진다.
ok(
  "전역 플래그(/g)를 쓰지 않는다",
  BASIS_CUES.every((c) => !c.test.global),
  BASIS_CUES.filter((c) => c.test.global).map((c) => c.label).join(","),
);
ok(
  "같은 글을 두 번 물어도 같은 답이다",
  JSON.stringify(basisLabels("제출 기한이 지났습니다")) ===
    JSON.stringify(basisLabels("제출 기한이 지났습니다")),
);
ok("빈 글에는 아무 이름표도 안 붙는다", basisLabels("").length === 0);

console.log(
  `\n${fails.length === 0 ? "전부 통과" : "실패"} — ${pass}건 통과, ${fails.length}건 실패`,
);
if (fails.length > 0) {
  for (const f of fails) console.log(`  · ${f}`);
  process.exit(1);
}
