/**
 * 자리표 — 목록 안에서 「여기」를 가리키는 값.
 *
 * ── 무엇을 푸는 값인가 ──────────────────────────────────────────────────────
 *
 * 두 사람이 같은 문단에 동시에 글자를 넣는다고 하자. 「3번째 자리에 ㄱ」
 * 「3번째 자리에 ㄴ」이라고 서로에게 알리면 받는 쪽에서 순서가 어긋난다.
 * 먼저 온 것을 반영하는 순간 뒤엣것의 「3번째」가 다른 곳을 가리키기 때문이다.
 * 서버가 줄을 세워 주면 되지만 우리에게는 그럴 서버가 없다 — Supabase 의
 * broadcast 는 신호를 옮길 뿐 순서를 보장하지 않는다.
 *
 * 그래서 자리를 **번호가 아니라 좌표**로 잡는다. 좌표는 한번 정해지면 남이
 * 무엇을 넣고 지우든 변하지 않고, 두 좌표 사이에는 언제나 새 좌표를 만들 수
 * 있다. 각자 자기 좌표를 정해 알리면 받는 쪽은 정렬만 하면 된다. 누가 먼저
 * 도착했는지, 몇 번 도착했는지가 결과에 영향을 주지 않는다.
 * (Logoot 계열. Yjs·Automerge 가 푸는 문제를 우리 규모로 줄인 것이다)
 *
 * ── 모양 ────────────────────────────────────────────────────────────────────
 *
 *   [[1024, "k3f9", 0], [37, "a1b2", 5]]
 *
 * 마디 하나가 `[숫자, 만든 자리, 그 자리의 일련번호]` 다. 사전식으로 비교하고,
 * 짧은 쪽이 앞선다.
 *
 * ── 왜 마디마다 「만든 자리」가 들어가는가 ──────────────────────────────────
 *
 * 처음에는 좌표를 순수한 숫자 배열로 두고 자리 이름을 **맨 끝에 한 번만**
 * 붙였다. 무작위 시험이 곧바로 반례를 뱉었다:
 *
 *   두 사람이 같은 틈에 동시에 글자를 넣으면 숫자 배열이 **같아진다.**
 *   (`[3]` 과 `[3]`, 자리 이름만 다름) 순서는 자리 이름으로 갈리지만,
 *   그 **둘 사이에** 다시 글자를 넣을 방법이 없다 — 숫자만으로는 둘이 같은
 *   자리이므로 사이가 없고, 더 깊이 파고들면 둘 다보다 커진다.
 *
 * 자리 이름이 마디마다 있으면 그 상황에서 「왼쪽 마디를 그대로 베껴 쓰고 한
 * 칸 내려가기」가 가능해진다. 남의 마디를 베끼는 것이 이상해 보이지만,
 * 앞자리는 순서를 정하는 접두사일 뿐이고 **마지막 마디만** 내 것이면 된다.
 *
 * ── 마지막 마디의 숫자는 1 이상이다 ─────────────────────────────────────────
 *
 * `[[1,…]]` 과 `[[1,…],[0,…]]` 사이에는 아무것도 만들 수 없다. 뒤엣것으로
 * 시작하는 좌표는 전부 그보다 크기 때문이다. 그런 막다른 골목이 한 번 생기면
 * 그 자리에는 영영 글자를 못 넣는다. **만들어 내는 좌표의 마지막 마디는 언제나
 * 1 이상**으로 둔다(중간 마디는 0 이어도 된다). 이 규칙 하나가 아래 `between`
 * 이 언제나 답을 찾는다는 것의 근거다 — 증명은 그 함수 주석에 적었다.
 */

/**
 * 한 마디가 가질 수 있는 숫자의 폭.
 *
 * 2^20. 넓을수록 좌표가 얕게 유지된다 — 한 마디가 다 차야 다음 마디로
 * 내려가기 때문이다. 실측으로 정했다: 2^16 이면 한 문단에 5만 자를 이어 칠 때
 * 깊이가 25까지 갔고, 2^20 이면 2 에서 멎는다. JSON 으로 적어도 일곱 자리라
 * 신호 크기에는 차이가 없다.
 */
const BASE = 1 << 20;

/**
 * 한 번에 벌리는 폭.
 *
 * 빈 곳 전체에서 고르게 뽑으면(순수 Logoot) 이어 쓰는 글에서 좌표가 금세
 * 깊어진다 — 앞의 것이 남긴 틈을 매번 절반씩 먹기 때문이다. 경계에 바짝
 * 붙여 조금씩만 벌리면(boundary 전략) 「위에서 아래로 쓰는」 실제 모양에서
 * 깊이가 거의 늘지 않는다.
 *
 * 1 이 아니라 32 인 이유는 동시 편집이다. 언제나 경계+1 을 고르면 두 사람이
 * 같은 틈에 넣을 때 반드시 같은 숫자가 나오고, 그러면 순서가 자리 이름으로만
 * 갈려 「먼저 친 사람의 글이 뒤로 밀리는」 일이 생긴다. 흩어 두면 대개 갈린다.
 */
const SPREAD = 32;

export type Site = string;

/** `[숫자, 만든 자리, 그 자리의 일련번호]` */
export type Ident = [number, Site, number];

/** 사전식으로 비교하는 마디 배열. */
export type Pos = Ident[];

function cmpIdent(a: Ident, b: Ident): number {
  if (a[0] !== b[0]) return a[0] < b[0] ? -1 : 1;
  if (a[1] !== b[1]) return a[1] < b[1] ? -1 : 1;
  if (a[2] !== b[2]) return a[2] < b[2] ? -1 : 1;
  return 0;
}

function sameIdent(a: Ident, b: Ident): boolean {
  return a[0] === b[0] && a[1] === b[1] && a[2] === b[2];
}

/** 사전식 비교. 0 이면 완전히 같은 자리표다. */
export function cmpPos(a: Pos, b: Pos): number {
  const min = a.length < b.length ? a.length : b.length;
  for (let i = 0; i < min; i += 1) {
    const c = cmpIdent(a[i], b[i]);
    if (c !== 0) return c;
  }
  return a.length === b.length ? 0 : a.length < b.length ? -1 : 1;
}

/**
 * 지도·집합의 열쇠로 쓸 문자열.
 *
 * ⚠ 이 문자열의 사전식 순서는 `cmpPos` 의 순서와 **다르다**(자릿수가 다르면
 * 어긋난다). 순서가 필요한 곳에서는 반드시 `cmpPos` 를 쓴다. 이 값은
 * 「같은 자리표인가」를 묻는 데만 쓴다.
 */
export function posKey(pos: Pos): string {
  let out = "";
  for (const [d, s, n] of pos) out += `${d}.${s}.${n}|`;
  return out;
}

/**
 * 두 좌표 사이의 새 좌표.
 *
 * `before` 가 null 이면 맨 앞, `after` 가 null 이면 맨 뒤라는 뜻이다.
 * 돌려주는 값은 언제나 `before < 결과 < after` 를 만족한다.
 *
 * ── 어떻게 도는가 ───────────────────────────────────────────────────────────
 *
 * 마디를 하나씩 내려가며 「여기에 끼울 숫자가 있나」를 묻는다. 있으면 끼우고
 * 끝, 없으면 왼쪽(before)의 마디를 그대로 베껴 한 칸 내려간다. 내려가는 도중
 * 두 좌표가 갈리면 그 아래로는 after 의 제약이 사라진다 — 이미 앞 마디에서
 * 작다는 것이 정해졌기 때문이다.
 *
 * ── 왜 반드시 끝나는가 ─────────────────────────────────────────────────────
 *
 * 1. 제약이 풀린 다음 마디에서는 상한이 BASE 이므로 언제나 끼울 숫자가 있다.
 * 2. 제약이 살아 있는 동안 out 은 after 의 앞부분과 글자 그대로 같다. 그런
 *    상태로 after 의 길이를 넘어설 수는 없다 — 넘어서려면 after 가 before 의
 *    앞부분이어야 하는데, 그건 after < before 라는 뜻이라 전제에 어긋난다.
 * 3. before 가 먼저 끝나고 제약이 남아 있으면 after 의 마디를 따라 내려간다.
 *    after 의 **마지막 마디는 숫자가 1 이상**이므로(위 불변식) 거기서는
 *    0 을 쓸 수 있어 반드시 답이 나온다.
 *
 * 즉 최대 `max(before.length, after.length) + 1` 번 돌고 끝난다.
 */
export function between(
  before: Pos | null,
  after: Pos | null,
  site: Site,
  seq: number,
  rand: () => number = Math.random,
): Pos {
  const lo = before ?? [];
  const hi = after;

  const out: Ident[] = [];
  /** after 가 아직 상한으로 살아 있는가. */
  let bounded = hi !== null;

  for (let i = 0; ; i += 1) {
    const li: Ident | undefined = i < lo.length ? lo[i] : undefined;
    const hj: Ident | undefined = bounded && i < hi!.length ? hi![i] : undefined;

    const l = li ? li[0] : 0;
    const h = hj ? hj[0] : BASE;

    if (h - l > 1) {
      // 끼울 자리가 있다. 어느 쪽에 바짝 붙일지는 **무엇을 하는 중인가**로 정한다.
      // 마디 하나가 아니라 부름 전체를 보고 정하는 것이 중요하다 — 한 마디가
      // 다 차서 아래로 내려온 뒤에도 같은 방향으로 계속 채워야 얕게 유지된다.
      //
      //   맨 뒤에 이어 쓴다(after 없음)    → 왼쪽에 바짝
      //   맨 앞에 끼운다(before 없음)      → 오른쪽에 바짝
      //   두 이웃 사이 = 타이핑             → 왼쪽에 바짝
      //   빈 목록의 첫 값(양쪽 다 없음)     → 한가운데
      //
      // 마지막이 왼쪽인 것이 중요하다. 문단 가운데에 「안녕하세요」를 치면
      // 매번 (직전 글자, 고정된 다음 글자) 사이에 넣게 되는데, 가운데를 고르면
      // 틈이 글자마다 절반으로 줄어 스무 자마다 좌표가 깊어진다.
      const room = h - l - 1; // 쓸 수 있는 숫자의 개수 (l+1 … h-1)
      const step = room < SPREAD ? room : SPREAD;

      let d: number;
      if (before === null && after === null) d = l + 1 + Math.floor(room / 2);
      else if (before === null) d = h - 1 - Math.floor(rand() * step);
      else d = l + 1 + Math.floor(rand() * step);

      out.push([d, site, seq]);
      return out;
    }

    if (li !== undefined) {
      // 이 마디에서는 못 끼운다. 왼쪽 마디를 그대로 베껴 한 칸 내려간다.
      out.push(li);
      if (bounded && !(hj !== undefined && sameIdent(li, hj))) bounded = false;
      continue;
    }

    // before 가 끝났다. 상한이 없으면 위에서 이미 돌아갔다(h - 0 = BASE > 1).
    // 그러므로 여기서는 반드시 hj 가 있다.
    if (h === 1) {
      // 0 을 쓸 수 있다. 다만 마지막 마디가 0 이면 불변식이 깨지므로
      // 한 마디를 더 붙여 끝을 1 이상으로 만든다.
      out.push([0, site, seq]);
      out.push([1 + Math.floor(BASE / 2), site, seq]);
      return out;
    }

    // h === 0 — 이 마디는 after 의 마지막이 아니다(불변식). 베끼고 내려간다.
    out.push(hj!);
  }
}

/**
 * 이미 있는 값 목록에 결정적인 좌표를 매긴다.
 *
 * ── 왜 이 함수가 있어야 하는가 ──────────────────────────────────────────────
 *
 * 편집을 시작할 때 문서는 DB 에서 온 평범한 배열이다. 여기에 좌표를 매겨야
 * 하는데, 각자 제멋대로 매기면 같은 문서를 열어도 서로 다른 좌표가 되어
 * 두 사람의 글이 뒤섞인다.
 *
 * 그래서 **아무나 매겨도 같은 값이 나오게** 한다. 난수를 안 쓰고, 자리 이름을
 * 고정값 `SEED_SITE` 로 두고, 일련번호는 순서 그대로 쓴다. 같은 스냅샷을 연
 * 두 사람은 반드시 같은 좌표를 얻는다 — 「누가 먼저 열어 기준을 잡느냐」는
 * 경쟁 자체가 사라진다. (use-collab.ts 의 합류 절차가 이것에 기대고 있다)
 *
 * 자리 이름을 `"~"` 로 둔 것도 뜻이 있다. 아스키에서 `~`(0x7e)는 영문 소문자
 * 뒤에 온다. 자리 이름은 소문자·숫자로만 만들므로(newSite), **같은 숫자를
 * 가진 마디에서 시드 좌표가 언제나 뒤로 밀린다.** 즉 사람이 만든 좌표가
 * 시드보다 앞선다 — 문서 맨 앞에 글을 보태는 흔한 동작이 얕게 끝난다.
 */
export const SEED_SITE: Site = "~";

/**
 * 간격을 고정하지 않고 폭 전체에 고르게 편다.
 *
 * 고정 간격(예: 1024)으로 두면 항목이 1024개를 넘는 순간 좌표가 BASE 를 넘어
 * 첫 마디가 통째로 쓸모없어진다 — 그 문서는 열자마자 한 칸 깊은 데서 시작한다.
 * 나눠 쓰면 어떤 크기의 문서든 첫 마디 안에서 끝나고, 이웃 사이에 남는 틈도
 * 항목 수에 맞춰 저절로 조절된다.
 */
export function seedPositions(count: number): Pos[] {
  if (count <= 0) return [];
  const step = Math.max(1, Math.floor(BASE / (count + 1)));
  const out: Pos[] = [];
  for (let i = 0; i < count; i += 1) out.push([[(i + 1) * step, SEED_SITE, i]]);
  return out;
}

/**
 * 이 자리를 가리키는 이름.
 *
 * 브라우저 탭 하나가 한 자리다. 같은 사람이 두 탭을 열면 두 자리가 되는데,
 * 그래야 맞다 — 한 사람이 두 탭에서 같은 문단을 고쳐도 글자가 섞이지 않는다.
 *
 * 사용자 id 를 쓰지 않는다. 자리 이름은 정렬의 갈림쇠로 **그 문서를 보는
 * 모두에게 그대로 전달되는** 값이라, 여기에 uuid 를 실으면 서로의 계정 id 를
 * 알게 된다. 누가 접속했는지는 그것대로 따로 알린다(work-live.tsx 의 주석).
 */
export function newSite(rand: () => number = Math.random): Site {
  const A = "0123456789abcdefghijklmnopqrstuvwxyz";
  let out = "";
  for (let i = 0; i < 6; i += 1) out += A[Math.floor(rand() * A.length)];
  return out;
}
