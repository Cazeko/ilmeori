/**
 * 검색어를 PostgREST 필터 값으로 만든다.
 *
 * ── 왜 이 파일이 생겼나 ────────────────────────────────────────────────────
 *
 * 업무 보드의 검색은 한동안 **전 행을 받아 온 뒤 자바스크립트에서** 걸렀다.
 * 그래서 조회에 상한을 걸 수가 없었다 — 100건만 받아서 그 안을 검색하면
 * 101번째 업무는 제목이 정확히 일치해도 안 나오고, 사용자는 없다고 믿는다.
 * 검색을 DB 로 내리는 것이 상한을 거는 일의 전제다.
 *
 * 그런데 PostgREST 의 `or=` 필터는 **문자열로 조립된다.** 사용자가 친 글자가
 * 그 문자열에 그대로 들어가므로, 여기가 이 저장소에서 사용자 입력이 질의
 * 문법과 만나는 몇 안 되는 자리다.
 *
 * ── 무엇을 막는가 ──────────────────────────────────────────────────────────
 *
 *   `,` `(` `)`   PostgREST 가 `or=(a,b)` 를 가르는 글자. 값 안에 들어가면
 *                 조건이 하나 더 생긴 것처럼 파싱될 수 있다
 *   `"` `\`       값을 겹따옴표로 감쌀 때의 탈출 문자
 *   `%` `_` `*`   ILIKE 의 와일드카드. 막지 않으면 `%` 한 글자를 친 사람에게
 *                 **전 행이** 돌아온다(상한을 건 의미가 사라진다)
 *
 * 탈출(escape)이 아니라 **제거**를 고른 이유가 있다. 탈출은 두 층을 겹쳐야
 * 하고(ILIKE 패턴 층 + PostgREST 값 층) 역슬래시가 층마다 불어나 사람이 읽고
 * 검산하기 어려워진다. 검색칸에 `%`·`"`·`(` 를 넣어야 하는 업무 검색은 없다.
 * 「50%」를 치면 「50」으로 찾고, 그 결과에 50% 문서가 포함된다 — 잃는 것이
 * 없다시피 하고, 대신 이 함수는 눈으로 안전을 확인할 수 있다.
 *
 * 값은 겹따옴표로 감싸서 돌려준다. 남은 글자에 공백이 있어도 값 하나로 읽힌다.
 */

/** 질의 문법과 부딪히거나 와일드카드로 동작하는 글자들. */
const UNSAFE = /[%_*"\\,()]/g;

/**
 * 「무엇을 찾는가」의 알맹이. 걸러낸 뒤 남는 것이 없으면 null.
 *
 * ── 두 구현이 이 함수를 함께 쓴다 ──────────────────────────────────────────
 *
 * Supabase 쪽은 이 값을 ilike 패턴으로 감싸고(아래), 목업 쪽은 그대로
 * `includes()` 에 넣는다. 처음에는 여기를 Supabase 전용으로 두고 목업은 날
 * 검색어를 그대로 썼는데, 그러면 **같은 입력에 두 구현이 다른 답**을 한다 —
 * `%` 한 글자를 치면 목업은 「그런 제목 없음」으로 0건, Supabase 는 걸러낸 뒤
 * 조건이 사라져 전체였다. `data/index.ts` 가 「어느 쪽 구현을 쓰든 화면은 같은
 * 답을 받는다」고 약속해 둔 것을 깨는 자리다.
 *
 * null 을 「빈 결과」가 아니라 **「조건 없음」**으로 읽는 것도 규칙이다.
 * 검색칸에 `%` 만 남은 것은 빈 칸과 같은 뜻이지 「아무것도 없다」가 아니다.
 */
export function searchTerm(raw: string | undefined | null): string | null {
  const clean = (raw ?? "").replace(UNSAFE, " ").replace(/\s+/g, " ").trim();
  return clean || null;
}

/** 그 알맹이를 PostgREST 값으로 감싼다 → `"%걸러낸말%"`. */
export function ilikePattern(raw: string | undefined | null): string | null {
  const term = searchTerm(raw);
  return term === null ? null : `"%${term}%"`;
}
