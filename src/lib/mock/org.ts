function buildDepartments(): Department[] {
  const rows: Department[] = [];
  let n = 0;
  for (const [bureau, divisions] of ORG) {
    n += 1;
    const parent = deptId(n);
    rows.push({
      id: parent,
      name: bureau,
      parent_id: null,
      // 과가 없는 실·국(감사관 등)은 그 자체가 실무 부서다.
      description: divisions.length === 0 ? (DUTY[bureau] ?? null) : null,
      sort_order: rows.length,
    });
    for (const division of divisions) {
      n += 1;
      rows.push({
        id: deptId(n),
        name: division,
        parent_id: parent,
        description: DUTY[division] ?? null,
        sort_order: rows.length,
      });
    }
  }
  return rows;
}

export const departments: Department[] = buildDepartments();

const byName = new Map(departments.map((d) => [d.name, d]));

/** 부서명으로 id를 얻는다. 목업을 쓸 때 UUID를 외울 필요가 없게 한다. */
export function dept(name: string): Department {
  const found = byName.get(name);
  if (!found) throw new Error(`목업 조직도에 없는 부서: ${name}`);
  return found;
}

