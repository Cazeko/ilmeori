/** 이 대화가 왜 현안으로 뽑혔는가. 하나도 안 걸리면 빈 배열. */
export function issueLabels(body: string): string[] {
  return ISSUE_CUES.filter((cue) => cue.test.test(body)).map((cue) => cue.label);
}

/**
 * 근거 꼬리표에 적을 갈래 이름들.
 *
 * 예전에는 이 목록이 `handover-draft.ts` 안에 **문자열로 박혀 있었고**, 그 문자열은
 * 이미 표와 어긋나 있었다(표는 「이견·유의」인데 꼬리표는 「이견」). 갈래를 하나
 * 고칠 때마다 두 곳을 맞춰야 하는 구조는 언젠가 반드시 어긋난다.
 *
 * 이름표에 이미 `·` 가 들어 있으므로(「이견·유의」) 이어 붙일 때도 `·` 를 쓰면
 * 갈래가 여섯 개로 읽힌다. 그래서 쉼표로 잇는다.
 */
export const ISSUE_CUE_NAMES = ISSUE_CUES.map((c) => c.label).join(", ");
