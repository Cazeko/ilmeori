/**
 * 결재 문서의 근거가 될 만한 대화를 고르는 규칙.
 *
 * ── 왜 파일이 따로인가 ─────────────────────────────────────────────────────
 *
 * 이 파일은 **바깥을 하나도 부르지 않는다.** `approval-export.ts` 는
 * `import "server-only"` 와 `@/` 별칭을 쓰므로 시험이 그대로 불러 돌릴 수 없다.
 * 이 표는 **온나라로 나가는 공문서에 무엇이 「근거」라는 이름표를 달고 실릴지**를
 * 혼자 정하는 자리이고, 시험이 못 닿는 곳에 둘 자리가 아니다.
 * (`hwpx/pack.ts` 를 한 파일로 둔 것과 같은 이유이고, 같은 방식으로 시험한다 —
 *  `npm run test:cues`)
 *
 * ── 인계서와 반대로, 여기서는 좁게 잡는다 ──────────────────────────────────
 *
 * 인계서(`handover-draft.ts`)에는 「없는 것을 넣는 실수보다 있는 것을 빠뜨리는
 * 실수가 비싸다」고 적었다. 인계서는 안에서 보는 문서라, 잘못 걸린 한 줄은
 * 읽는 사람이 두 초 만에 넘기면 그만이기 때문이다.
 *
 * **결재 문서는 건물 밖으로 나간다.** 온나라에 올라가고 감사에 남는다. 거기에
 * 상관없는 대화 한 줄이 「근거」라는 이름표를 달고 실리는 것은, 근거 한 줄이
 * 빠지는 것보다 훨씬 비싸다. 그래서 같은 제품의 두 규칙이 서로 반대 방향으로
 * 기울어 있고, 그건 실수가 아니라 문서의 쓰임이 다르기 때문이다.
 *
 * ── 두 번 물렸다 ───────────────────────────────────────────────────────────
 *
 * ① 「까지·일정·법」을 낱말 그대로 잡았더니 *"정기인사로 이 업무를 이하람
 *    주무관에게 넘기게 됐습니다"* 가 「기한」 근거로 결재 문서에 실렸다.
 * ② 그걸 고친 뒤에도 **「기한」이 맨몸이라 「얘기한·이야기한·제기한·포기한·
 *    연기한·무기한」에 전부 걸렸다.** *"아까 얘기한 대로 진행하겠습니다"* 가
 *    근거가 된다. 억지 문장이 아니라 평범한 업무 어투다. 「좁게 잡았다」고
 *    적어 놓고 인계서(`기한이 |마감이 `)보다 **더 넓은** 상태였다.
 *
 * 그래서 낱말 앞뒤에 경계를 준다. 한국어에는 낱말 경계(`\b`)가 없으므로
 * **앞에 한글이 오면 안 된다**(`(?<![가-힣])`)로 대신한다.
 *
 * ⚠ 조사를 열거하는 방식(`기한(이|은|을|까지)`)으로 가면 안 된다.
 * 시연 데이터의 유일한 진짜 「기한」 근거가 *"요구서 제출 기한과 겹칩니다"* 라
 * 그 목록에 없는 조사에서 근거가 통째로 사라진다. 시험이 그것을 못박고 있다.
 */

export type BasisCue = { label: string; test: RegExp };

export const BASIS_CUES: readonly BasisCue[] = [
  {
    label: "협의",
    // 「종합의견·통합의료」의 「합의」, 「회의실」의 「회의」를 걸러야 한다.
    test: /(?<![가-힣])(협의|합의|회의(?!실)|간담회|조율|협조\s?요청)/,
  },
  {
    label: "확인·회신",
    test: /확인(했|하였|함|됨|됐|되었)|검토(했|하였|함|됨|됐|되었|\s?결과)|회신(했|하|받)/,
  },
  {
    label: "법령·기준",
    // 「법」은 「방법·법인·헌법소원」에도 들어간다. 낫표 안이나 「제○조」 꼴만 본다.
    test: /「[^」]*(법|령|규칙|조례|지침|고시|규정)」|시행령|시행규칙|제\s?\d+\s?조/,
  },
  {
    // 「4장」·「3건」은 수치가 아니라 세는 말이다. 돈·비율·물량만 본다.
    label: "금액·수치",
    test: /\d[\d,]*\s*(원|만원|억원|%|퍼센트|톤|㎡)/,
  },
  {
    label: "기한",
    // 앞경계가 기본이다 — 「무기한·얘기한·이야기한·제기한·포기한·연기한」이
    // 전부 「기한」을 품고 있고, 전부 이 결재의 근거가 아니다.
    //
    // 그러면 「제출기한」처럼 **붙여 쓰는 진짜 낱말**이 함께 빠진다. 두 목록 중
    // 어느 쪽도 닫혀 있지 않으므로, 기본은 안전한 쪽(앞경계)으로 두고 행정
    // 문서에서 실제로 쓰는 합성어만 이름을 불러 되살린다. 빠뜨리는 쪽이
    // 잘못 싣는 쪽보다 싸다는 이 파일의 방향과 같다.
    test: /(?<![가-힣])(기한|마감(?!재)|납기|제출일)|(제출|납품|처리|신청|접수|이행)기한/,
  },
  {
    // 「8월 8일까지 반영본을 받기로 했으니」 — 이 결재 뒤에 이어질 약속.
    label: "약속",
    test: /기로\s?(했|하였|함|됐|되었)|드리겠습니다|보고드리/,
  },
];

/** 이 대화가 왜 근거로 뽑혔는가. 하나도 안 걸리면 빈 배열. */
export function basisLabels(body: string): string[] {
  return BASIS_CUES.filter((cue) => cue.test.test(body)).map((cue) => cue.label);
}
