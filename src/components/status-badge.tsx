import { STATUS_LABEL, type DerivedStatus } from "@/lib/types";

/**
 * 상태 배지 — 일머리의 중심 색 언어.
 *
 * 이 제품은 "업무가 지금 어디까지 왔는지"를 보여주는 도구이므로,
 * 상태 표현이 화면 전체에서 한 치도 어긋나면 안 된다.
 *
 * 색만으로 구분하지 않는다 — 레이블 텍스트를 항상 함께 제공한다(접근성).
 *
 * ── 다섯 색에서 한 색으로 ───────────────────────────────────────────────────
 *
 * 예전에는 다섯 상태에 다섯 색을 줬다(회색·파랑·황토·초록·빨강). KRDS 시스템
 * 색상 의미 체계에서 곧이곧대로 파생한 것이라 하나하나는 옳았는데, 한 화면에
 * 다섯이 함께 놓이자 **완료(초록)가 지연(빨강)만큼 눈에 띄었다.** 다섯이 다
 * 튀면 아무것도 튀지 않는다.
 *
 * 상태는 대부분 「구분」이지 「경고」가 아니다. 경고인 것은 지연 하나뿐이다.
 * 그래서 색은 지연에만 남기고, 나머지 넷은 **명도로 나눈다.**
 *
 *   진행중  가장 진하다 — 지금 움직이고 있는 것
 *   검토    그 다음
 *   대기    옅다 — 아직 시작하지 않은 것
 *   완료    가장 옅다 — 끝나서 물러난 것
 *
 * 색이 아니라 명도로 나누면 위계가 「무엇이 급한가」 축에 정렬된다. 그리고
 * 화면에 붉은 것이 하나뿐이면, 그것이 곧 유일한 신호가 된다.
 *
 * ── 면을 걷어냈다 ──────────────────────────────────────────────────────────
 *
 * 명도로 나누는 데까지 왔으면서도 **네 상태 모두 옅은 회색 면을 깔고 있었다.**
 * 그러면 위계가 두 번 말해진다 — 글자색으로 한 번, 바탕으로 또 한 번. 그리고
 * 보드 한 화면에 그 네모가 서른 개 서면, 눈에 남는 것은 상태가 아니라 **네모의
 * 격자**다. 「무엇이 핵심이고 무엇이 보조인지 시선이 안 간다」는 말이 이 자리에도
 * 걸린다. 면은 화면에서 가장 비싼 표현 수단이라, 상태 같은 곁정보가 쓸 것이 아니다.
 *
 * 면을 지우면 명도 사다리가 유일한 축이 된다. 한동안 네 칸(90 · 80 · 70 · 60)
 * 이었는데, 80 과 90, 60 과 70 은 13px 굵은 글자에서 눈이 가르지 못하는
 * 차이였다 — 네 단이라고 적어 두고 실제로는 두 단으로 보였다. 그래서 두 단으로
 * 못박는다: **지금 손에 있는 것**(진행중·검토)은 먹색, **손에 없는 것**(대기·
 * 완료)은 회색. 넷을 가르는 일은 글자(「대기」「완료」)가 하고, 명도는
 * 「지금 움직이는 것인가」 하나만 답한다. 배지는 점 하나와 글자다.
 * (글자 회색을 90·60·40 셋으로 묶은 규칙은 tests/design-lint.test.mjs 에.)
 *
 * 대비는 tests/contrast.test.mjs 가 잰다. 재는 바탕이 바뀌었다 — 예전에는 자기
 * 채움(gray-5·gray-10) 위에서 쟀지만, 이제는 판(surface)과 본문 바탕(gray-5)
 * 위에 그대로 얹히므로 **그 둘 위에서** 잰다.
 */

const TONE: Record<DerivedStatus, string> = {
  todo: "text-gray-60",
  doing: "text-gray-90",
  review: "text-gray-90",
  done: "text-gray-60",
  overdue: "text-status-overdue-text", // 유일한 색
};

export function StatusBadge({
  status,
  size = "md",
}: {
  status: DerivedStatus;
  size?: "sm" | "md";
}) {
  return (
    <span
      className={[
        "inline-flex items-center gap-2 font-bold whitespace-nowrap",
        size === "sm" ? "text-body-xs" : "text-body-sm",
        TONE[status],
      ].join(" ")}
    >
      {/* 점은 장식이 아니라 스캔 속도를 위한 것. 스크린리더에서는 숨긴다. */}
      <span aria-hidden className="size-1.5 rounded-full bg-current" />
      {STATUS_LABEL[status]}
    </span>
  );
}
